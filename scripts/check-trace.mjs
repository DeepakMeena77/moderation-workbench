#!/usr/bin/env node
// Traceability: every acceptance criterion in docs/01-requirements.md should have at least one test whose
// name contains "[ID]" under tests/ or evals/.
// Usage: node scripts/check-trace.mjs [--slice S3] [--strict]
// Writes docs/trace.md (copy it into the README evidence table).

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = process.cwd();
const args = process.argv.slice(2);
const strict = args.includes('--strict');
const sliceIndex = args.indexOf('--slice');
const slice = sliceIndex >= 0 ? args[sliceIndex + 1] : null;

// Proven by documents or the deployment rather than by an automated test.
const MANUAL = (id) => id.startsWith('DOC-') || id === 'OPS-5';

function readCriteria() {
  const text = readFileSync(join(root, 'docs/01-requirements.md'), 'utf8');
  const criteria = [];
  for (const line of text.split('\n')) {
    const match = /^\|\s*([A-Z]{1,5}-\d+)\s*\|\s*(.*?)\s*\|/.exec(line);
    if (match) criteria.push({ id: match[1], text: match[2].replace(/\*\*/g, '') });
  }
  return criteria;
}

function expandIds(text) {
  const ids = new Set();
  for (const match of text.matchAll(/([A-Z]{1,5})-(\d+)(?:\.\.(?:[A-Z]{1,5}-)?(\d+))?/g)) {
    const [, prefix, from, to] = match;
    const end = to ? Number(to) : Number(from);
    for (let n = Number(from); n <= end; n++) ids.add(`${prefix}-${n}`);
  }
  return ids;
}

function sliceIds(name) {
  const plan = readFileSync(join(root, 'docs/04-build-plan.md'), 'utf8');
  const start = plan.search(new RegExp(`^## ${name}\\b`, 'm'));
  if (start < 0) throw new Error(`Slice ${name} not found in docs/04-build-plan.md`);
  const rest = plan.slice(start + 3);
  const end = rest.search(/^## /m);
  const section = end >= 0 ? rest.slice(0, end) : rest;
  const line = section.split('\n').find((l) => l.startsWith('**Acceptance:**'));
  if (!line) throw new Error(`No **Acceptance:** line in slice ${name}`);
  return expandIds(line);
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'results') continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (/\.(ts|tsx|js|mjs|json)$/.test(entry.name)) files.push(full);
  }
  return files;
}

let criteria = readCriteria();
if (slice) {
  const ids = sliceIds(slice);
  criteria = criteria.filter((c) => ids.has(c.id));
}

const testFiles = [...walk(join(root, 'tests')), ...walk(join(root, 'evals'))].map((file) => ({
  file: relative(root, file).split(sep).join('/'),
  text: readFileSync(file, 'utf8'),
}));

const rows = criteria.map((c) => {
  const files = testFiles.filter((t) => t.text.includes(`[${c.id}]`)).map((t) => t.file);
  const status = files.length > 0 ? 'covered' : MANUAL(c.id) ? 'manual' : 'missing';
  return { ...c, files, status };
});

const missing = rows.filter((r) => r.status === 'missing');
const covered = rows.filter((r) => r.status === 'covered');

const short = (s) => (s.length > 90 ? `${s.slice(0, 87)}...` : s).replace(/\|/g, '/');
const table = [
  '| ID | Criterion | Evidence (tests) | Status |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.id} | ${short(r.text)} | ${r.files.join(', ') || '-'} | ${r.status} |`),
].join('\n');

if (!slice) {
  const header = '# Traceability (generated by scripts/check-trace.mjs; do not edit by hand)\n\n';
  writeFileSync(join(root, 'docs/trace.md'), `${header}${table}\n`, 'ascii');
}

console.log(table);
console.log(
  `\ncheck-trace${slice ? ` (${slice})` : ''}: ${covered.length} covered, ` +
    `${rows.length - covered.length - missing.length} manual, ${missing.length} missing of ${rows.length}.`,
);
if (missing.length > 0) console.log(`Missing: ${missing.map((r) => r.id).join(', ')}`);
if (strict && missing.length > 0) process.exit(1);
